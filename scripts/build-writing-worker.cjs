/* Generate a trusted worker source string for Chrome's file:// entry point.
 * The bundle is loaded as a normal local script; no runtime file read or eval
 * permission is needed. Run --check to reject a stale generated source. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = ['model.js', 'fdx.js', 'pagination.js'];
const source = files.map(name => `/* ${name} */\n${fs.readFileSync(path.join(root, 'app/js', name), 'utf8')}`).join('\n;\n') +
  '\n;\n' + fs.readFileSync(path.join(root, 'app/js/pagination-worker.js'), 'utf8').replace(/^importScripts\([^\n]*\);\s*$/m, '');
const output = '/* Generated by scripts/build-writing-worker.cjs. Do not edit by hand. */\n' +
  `self.FDPaginationWorkerSource = ${JSON.stringify(source).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')};\n`;
const destination = path.join(root, 'app/js/pagination-worker-source.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    console.error('FAIL: pagination worker source is stale. Run node scripts/build-writing-worker.cjs.'); process.exitCode = 1;
  } else console.log('PASS: trusted pagination worker source matches current modules');
} else {
  fs.writeFileSync(destination, output, 'utf8');
  console.log(`Built trusted pagination worker source (${Buffer.byteLength(source)} bytes)`);
}
