/* Keep every surface showing one glyph family, generated, never hand-copied.
 *
 * app/brand/azkript-mark.svg       — the master tile glyph (32 px and up)
 * app/brand/azkript-mark-small.svg — optical size for 16-24 px slots
 *
 * Both are injected into app/index.html as `#i-app-mark` and
 * `#i-app-mark-small` between the brand:mark markers, and the desktop icon set is
 * rasterised from the same two files by scripts/make-icon.py. So the titlebar
 * lockup, the Start Center lockup, the taskbar icon and the installer icon are
 * four renders of one drawing rather than four drawings of one idea.
 *
 * The small variant re-declares the same gradient ids as the master; they are
 * namespaced on injection so the two copies do not collide in one document
 * (duplicate ids are invalid, and whichever came first would silently win).
 *
 * Usage: node scripts/sync-brand.cjs [--check]
 *   --check  exit 1 if index.html is out of date (for tests/CI)
 */
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const htmlPath = path.join(root, "app", "index.html");

const START_PREFIX = "<!-- brand:mark:start";
const START = `${START_PREFIX} — generated by scripts/sync-brand.cjs from app/brand/azkript-mark*.svg -->`;
const END = "<!-- brand:mark:end -->";

/** Read one master SVG and split it into re-usable defs + body. */
function readMaster(relPath) {
  const file = path.join(root, relPath);
  const svg = fs.readFileSync(file, "utf8");

  const defsMatch = svg.match(/<defs>([\s\S]*?)<\/defs>/);
  if (!defsMatch) throw new Error(`${relPath}: no <defs> block`);
  const bodyMatch = svg.match(/<\/defs>([\s\S]*?)<\/svg>/);
  if (!bodyMatch) throw new Error(`${relPath}: no drawable body`);

  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1];
  if (viewBox !== "0 0 48 48") {
    throw new Error(`${relPath}: expected viewBox "0 0 48 48", found "${viewBox}"`);
  }

  const indent = (text, pad) =>
    text
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean)
      .map((line) => pad + line)
      .join("\n");

  return { defs: defsMatch[1].trim(), body: bodyMatch[1].trim(), viewBox };
}

/** Suffix every id and every url(#id) reference so two variants can coexist. */
function namespace(markup, suffix) {
  if (!suffix) return markup;
  const ids = new Set();
  for (const match of markup.matchAll(/\sid="([^"]+)"/g)) ids.add(match[1]);
  let out = markup;
  for (const id of ids) {
    out = out.split(`id="${id}"`).join(`id="${id}${suffix}"`);
    out = out.split(`url(#${id})`).join(`url(#${id}${suffix})`);
    out = out.split(`href="#${id}"`).join(`href="#${id}${suffix}"`);
  }
  return out;
}

function symbol(id, relPath, suffix) {
  const { defs, body, viewBox } = readMaster(relPath);
  return [
    `    <!-- ${path.basename(relPath)} -->`,
    "    <defs>",
    namespace(defs, suffix)
      .split("\n")
      .map((line) => "      " + line.trim())
      .filter((line) => line.trim())
      .join("\n"),
    "    </defs>",
    `    <symbol id="${id}" viewBox="${viewBox}">`,
    namespace(body, suffix)
      .split("\n")
      .map((line) => "      " + line.trim())
      .filter((line) => line.trim())
      .join("\n"),
    "    </symbol>",
  ].join("\n");
}

function block() {
  return [
    START,
    symbol("i-app-mark", "app/brand/azkript-mark.svg", ""),
    symbol("i-app-mark-small", "app/brand/azkript-mark-small.svg", "-sm"),
    `    ${END}`,
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const html = fs.readFileSync(htmlPath, "utf8");

  // Match the start marker by prefix: the text after it records which generator
  // wrote it, and an older generator's wording must still be replaceable.
  const startAt = html.indexOf(START_PREFIX);
  const endAt = html.indexOf(END);
  if (startAt === -1 || endAt === -1) {
    throw new Error(
      `brand:mark markers not found in app/index.html — expected:\n${START_PREFIX} ... -->\n...\n${END}`
    );
  }

  const next = html.slice(0, startAt) + block() + html.slice(endAt + END.length);
  if (next === html) {
    console.log("brand marks already in sync");
    return;
  }
  if (check) {
    console.error("brand marks OUT OF SYNC with app/brand/*.svg — run: node scripts/sync-brand.cjs");
    process.exitCode = 1;
    return;
  }
  fs.writeFileSync(htmlPath, next);
  console.log("synced #i-app-mark + #i-app-mark-small into app/index.html");
}

main();
